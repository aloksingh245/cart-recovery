"""Single source for initial PostgreSQL schema and the field-level dictionary.

The migration and dictionary are generated by scripts/build_schema.py.
Business invariants spanning rows are specified in docs/domain-rules.md.
"""

TABLES = []


def field(name, sql_type="text", *, required=True, pk=False, unique=False,
          fk=None, allowed=None, units="none", rule="non-empty text", check=None):
    return dict(name=name, type=sql_type, required=required, pk=pk, unique=unique,
                fk=fk, allowed=allowed, units=units, rule=rule, check=check)


def key(name, prefix):
    return field(name, pk=True, rule=f"immutable deterministic ID; {prefix}",
                 check=f"{name} ~ '{prefix}'")


def ref(name, target, required=True):
    return field(name, fk=target, required=required, rule=f"must exist in {target}; RESTRICT deletion")


def stamp(name, rule="timezone-aware UTC instant; ISO-8601 export"):
    return field(name, "timestamptz", units="UTC instant", rule=rule)


def enum(name, values):
    return field(name, allowed=values.split("|"), rule="exactly one allowed enum")


def num(name, units="count", minimum=0):
    return field(name, "bigint", units=units, rule=f"integer >= {minimum}",
                 check=f"{name} >= {minimum}")


def table(name, fields, constraints=(), immutable=True):
    TABLES.append(dict(name=name, fields=fields, constraints=list(constraints), immutable=immutable))


