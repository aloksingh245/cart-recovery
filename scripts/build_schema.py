"""Regenerate checked-in SQL and CSV dictionary. --check rejects drift."""
import argparse
import csv
import importlib.util
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("catalog", ROOT / "db/catalog.py")
catalog = importlib.util.module_from_spec(spec)
spec.loader.exec_module(catalog)


def render():
    sql = ["-- Generated by scripts/build_schema.py; change db/catalog.py.\nBEGIN;"]
    buf = io.StringIO(newline="")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["entity", "field", "sql_type", "required", "allowed_values", "units",
                     "uniqueness", "foreign_key", "validation_rule", "sql_check", "table_constraints"])
    for table in catalog.TABLES:
        columns = []
        for f in table["fields"]:
            col = f"  {f['name']} {f['type']}"
            if f["pk"]:
                col += " PRIMARY KEY"
            elif f["required"]:
                col += " NOT NULL"
            if f["unique"]:
                col += " UNIQUE"
            if f["fk"]:
                parent, key = f["fk"].split(".")
                col += f" REFERENCES {parent}({key}) ON DELETE RESTRICT"
            checks = []
            if f["allowed"]:
                checks.append(f"{f['name']} IN (" + ", ".join("'"+v+"'" for v in f["allowed"]) + ")")
            if f["check"]:
                checks.append(f["check"])
            if f["type"] == "text":
                checks.append(f"length(trim({f['name']})) > 0")
            for check in checks:
                col += f" CHECK ({check})"
            columns.append(col)
            writer.writerow([table["name"], f["name"], f["type"], f["required"],
                             "|".join(f["allowed"] or []), f["units"],
                             "PRIMARY KEY" if f["pk"] else "UNIQUE" if f["unique"] else "see table constraints",
                             f["fk"] or "", f["rule"], " AND ".join(checks),
                             "; ".join(table["constraints"])])
        columns.extend("  " + c for c in table["constraints"])
        sql.append(f"CREATE TABLE {table['name']} (\n" + ",\n".join(columns) + "\n);")
    sql.extend(c + ";" for c in catalog.INDEXES)
    sql.append("""CREATE FUNCTION reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'append-only relation: %', TG_TABLE_NAME;
END;
$$;""")
    for table in catalog.TABLES:
        if table["immutable"]:
            sql.append(f"CREATE TRIGGER {table['name']}_immutable BEFORE UPDATE OR DELETE ON {table['name']} "
                       "FOR EACH ROW EXECUTE FUNCTION reject_history_mutation();")
    sql.append("COMMIT;\n")
    return {ROOT / "db/001_initial.sql": "\n\n".join(sql),
            ROOT / "docs/data-dictionary.csv": buf.getvalue()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in render().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"drift: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
        print(f"{'checked' if args.check else 'wrote'} {path.relative_to(ROOT)}")
